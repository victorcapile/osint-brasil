const COMPILED_GENRES = GENRE_RULES.map((rule) => ({
  genre: rule.genre,
  strong: compile(rule.strong),
  weak: compile(rule.weak),
}));

const GENRE_PRIORITY: Genre[] = [
  "seguranca",
  "geopolitica",
  "negocios",
  "ciencia",
  "tecnologia",
  "saude",
  "esportes",
  "geral",
];

function scoreGenres(text: string, hint: Genre | undefined) {
  const scores = new Map<Genre, number>();
  const matches: Record<string, { strong: string[]; weak: string[] }> = {};

  if (hint) scores.set(hint, 2);

  for (const rule of COMPILED_GENRES) {
    let score = scores.get(rule.genre) ?? 0;
    const strong = rule.strong.filter((term) => text.includes(term));
    const weak = rule.weak.filter((term) => text.includes(term));
    score += strong.length * 3 + weak.length;
    scores.set(rule.genre, score);
    matches[rule.genre] = {
      strong: strong.map((term) => term.trim()),
      weak: weak.map((term) => term.trim()),
    };
  }

  return { scores, matches };
}

function detectGenre(text: string, hint: Genre | undefined): Genre {
  const { scores } = scoreGenres(text, hint);

  let best: Genre = "geral";
  let bestScore = 1.5;

  for (const genre of GENRE_PRIORITY) {
    const score = scores.get(genre) ?? 0;
    if (score > bestScore) {
      best = genre;
      bestScore = score;
    }
  }

  return best;
}

/** Ferramenta de calibração: mostra a pontuação e os termos que casaram. */
export function explainGenre(title: string, description: string, source: FeedSource) {
  const text = pad(`${title} ${title} ${description}`);
  const { scores, matches } = scoreGenres(text, source.genreHint);
  return {
    genre: detectGenre(text, source.genreHint),
    scores: Object.fromEntries(scores),
    matches,
  };
}

