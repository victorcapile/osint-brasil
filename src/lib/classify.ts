  const text = pad(`${title} ${title} ${description}`);

  const geography = detectCountryAndContinent(
    text,
    raw,
    source.defaultContinent,
  );
  const continent = geography.continent;
  // Notícia nacional sem país explícito: o país é o Brasil.
  const country = geography.country ?? (continent === "brasil" ? "BR" : null);
